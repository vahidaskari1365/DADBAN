function score(text: string, entry: KnowledgeEntry): number {
  const t = text.toLowerCase();
  let scoreVal = 0;
  for (const kw of entry.keywords) {
    if (text.includes(kw)) scoreVal += kw.length > 3 ? 3 : 2;
  }
  return scoreVal;
}

export function analyzeLegalQuery(query: string): LegalGuidance {
  const text = (query || "").trim();
  if (!text) return DEFAULT_GUIDANCE;

  let best: KnowledgeEntry | null = null;
  let bestScore = 0;
  for (const entry of KNOWLEDGE) {
    const s = score(text, entry);
    if (s > bestScore) {
      bestScore = s;
      best = entry;
    }
  }

  if (!best || bestScore < 2) return DEFAULT_GUIDANCE;

  return {
    topic: best.topic,
    matched: true,
    confidence: Math.min(0.95, 0.5 + bestScore * 0.12),
    summary: best.summary,
    steps: best.steps,
    documents: best.documents,
    risks: best.risks,
    laws: best.laws,
    articles: best.articles,
    nextActions: best.nextActions,
  };
}

export interface ClauseFinding {
  type: "risk" | "info";
  label: string;
  detail: string;
}

// Lightweight contract analysis: scans uploaded text for risky clauses.
export function analyzeContract(text: string): {
  findings: ClauseFinding[];
  riskScore: number;
} {
  const t = text || "";
  const findings: ClauseFinding[] = [];
  let riskScore = 0;

  const checks: { pattern: RegExp; label: string; detail: string }[] = [
    {
      pattern: /(فسخ|فسخ یک‌طرفه|حق فسخ).*(یک‌طرفه|انحصاری)/,
      label: "حق فسخ یک‌طرفه",
      detail: "این بند به یک طرف حق فسخ انحصاری می‌دهد و می‌تواند نامتعادل باشد.",
    },
    {
      pattern: /(جریمه|غرامت).{0,40}(روزانه|هر روز|به ازای)/,
      label: "جریمه روزانه سنگین",
      detail: "جریمه‌های روزانه باید متناسب باشند؛ رقم بالا ریسک مالی شدیدی ایجاد می‌کند.",
    },
    {
      pattern: /(تمام|همه|کلیه).*(خسارت|ضرر|زیان)/,
      label: "مسئولیت نامحدود",
      detail: "پذیرش مسئولیت نامحدود خسارت خطرناک است؛ سقف مسئولیت تعیین کنید.",
    },
    {
      pattern: /(تاریخ|مهلت|سررسید)/,
      label: "بندهای زمانی",
      detail: "تاریخ‌ها و سررسیدها را دقیقاً مشخص کنید تا ابهام نباشد.",
    },
    {
      pattern: /(محرمانگی|confidential)/,
      label: "بند محرمانگی",
      detail: "محدوده و مدت تعهد محرمانگی را بازبینی کنید.",
    },
    {
      pattern: /(حل‌.*اختلاف|داوری|مرجع رسیدگی)/,
      label: "شرط حل اختلاف",
      detail: "در نبود شرط داوری، اختلافات به دادگاه‌های عمومی کشیده می‌شوند.",
    },
    {
      pattern: /(تمدید خودکار|تمدید خود‌به‌خود)/,
      label: "تمدید خودکار",
      detail: "بند تمدید خودکار قرارداد را بدون اطلاع شما تمدید می‌کند.",
    },
  ];

  for (const c of checks) {
    if (c.pattern.test(t)) {
      const isRisk = !/زمانی|محرمانگی/.test(c.label);
      if (isRisk) riskScore += 1;
      findings.push({ type: isRisk ? "risk" : "info", label: c.label, detail: c.detail });
    }
  }

  if (findings.length === 0) {
    findings.push({
      type: "info",
      label: "بررسی اولیه",
      detail: "هیچ الگوی پرریسک شناخته‌شده‌ای یافت نشد. با این حال بازبینی توسط وکیل ضروری است.",
    });
  }

  return { findings, riskScore };
}
