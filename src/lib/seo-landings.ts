export function getSpecialtyLanding(slug: string): SpecialtyLanding | undefined {
  return SPECIALTY_LANDINGS.find((s) => s.slug === slug);
}

export function getCityLanding(slug: string): CityLanding | undefined {
  return CITY_LANDINGS.find((c) => c.slug === slug);
}

