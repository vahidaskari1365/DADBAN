export type CourtSpeaker = "judge" | "opponent" | "lawyer" | "system";

/** پیام خروجی مدل را به پیام‌های نقش‌دار می‌شکند */
export function parseCourtSpeakers(raw: string): { speaker: CourtSpeaker; text: string }[] {
  const out: { speaker: CourtSpeaker; text: string }[] = [];
  const lines = raw.replace(/\r\n/g, "\n").split("\n").filter((l) => l.trim().length > 0);
  let current: CourtSpeaker | null = null;
  for (const line of lines) {
    const t = line.trim();
    if (/^(قاضی)\s*[:：]/.test(t) || t.startsWith("قاضی محترم") || t.startsWith("قاضی:")) {
      current = "judge";
      out.push({ speaker: current, text: t.replace(/^(قاضی)\s*[:：]\s*/, "") });
    } else if (/^(وکیل\s*خصم)\s*[:：]/.test(t) || /^(وکیل\s*مدافع\s*خصم)\s*[:：]/.test(t)) {
      current = "opponent";
      out.push({ speaker: current, text: t.replace(/^(وکیل\s*(خصم|مدافع\s*خصم))\s*[:：]\s*/, "") });
    } else if (current) {
      // ادامهٔ پیام همان نقش
      out[out.length - 1].text += "\n" + t;
    } else {
      // بدون برچسب — احتیاط: قاضی (شروع معمول با قاضی است)
      current = "judge";
      out.push({ speaker: "judge", text: t });
    }
  }
  return out.filter((m) => m.text.trim().length > 0);
}
