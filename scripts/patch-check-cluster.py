Z = "\u200c"  # نیم‌فاصله

def rep(old, new, expect=1, name=""):
    global data
    n = data.count(old)
    if n != expect:
        print(f"FAIL [{name}] count={n} (expected {expect})")
        sys.exit(1)
    data = data.replace(old, new)
    print(f"OK   [{name}]")

