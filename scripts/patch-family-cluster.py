def rep(old, new, name, expect=1):
    global src
    n = src.count(old)
    if n != expect:
        print(f"FAIL [{name}] count={n} (expected {expect})")
        sys.exit(1)
    src = src.replace(old, new)
    print(f"OK   [{name}]")

